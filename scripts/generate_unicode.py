"""Reproduce Unicode property data for the XSD regular-expression engine.

Requires Python with Unicode 13.0.0 and the official Blocks-13.0.0.txt file.
Run: python scripts/generate_unicode.py path/to/Blocks.txt
Generated data is covered by third_party/UNICODE-LICENSE.txt.
"""
from pathlib import Path
import sys
import unicodedata

assert unicodedata.unidata_version == "13.0.0", "use Python 3.9 Unicode 13.0.0"
root = Path(__file__).resolve().parents[1]
blocks = Path(sys.argv[1]).read_text(encoding="utf-8")
assert "Blocks-13.0.0.txt" in blocks
rows = []
start = 0
previous = unicodedata.category(chr(0))
for code in range(1, 0x110001):
    category = unicodedata.category(chr(code)) if code < 0x110000 else None
    if category != previous:
        rows.append(f'  ({start}, {code-1}, "{previous}"),')
        start, previous = code, category
out = ["///|", "// Generated by scripts/generate_unicode.py; Unicode 13.0.0.",
       "// See third_party/UNICODE-LICENSE.txt for data copyright and permission.",
       "let unicode_categories : Array[(Int32, Int32, String)] = [", *rows, "]", "", "///|",
       "let unicode_blocks : Array[(String, Int32, Int32)] = ["]
for line in blocks.splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    span, name = line.split(";")
    lo, hi = span.split("..")
    name = name.strip().replace(" ", "")
    out.append(f'  ("{name}", {int(lo,16)}, {int(hi,16)}),')
out.extend(["]", ""])
(root / "unicode_data.mbt").write_text("\n".join(out), encoding="utf-8")
print(f"generated {len(rows)} category ranges")
